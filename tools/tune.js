#!/usr/bin/env node
/* Stage tuner: writes js/tune.js, the per-stage enemy strength and tower health multipliers.
 *   node tools/tune.js [difficulties=0,1,2]
 * For each story stage it finds the strongest Gloom that the scripted player (tools/sim.js) still beats at the
 * target hero level for that stage, keeps a 12% margin, then sizes the tower so the fight lasts about the target time.
 * Targets rise smoothly through the campaign, so difficulty does too.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const AW = require('../js/core.js');
const { playBattle } = require('./sim.js');
const { setup } = require('./calibrate.js');

const NORMAL = [[1, 6], [5, 11], [10, 15], [14, 19], [18, 23], [22, 27], [26, 31], [30, 36]];
// Chapter 1 as before; chapters 2 and 3 keep climbing (36 to 44, then 44 to 50) with heroes capped at level 50.
function targetLevel(d, r, i) {
  const k = i / 11;
  if (d === 0) {
    if (r < 8) return Math.round(NORMAL[r][0] + (NORMAL[r][1] - NORMAL[r][0]) * k);
    if (r < 16) return Math.round(36 + (r - 8) + k);
    return Math.min(50, Math.round(44 + (r - 16) * 0.8 + k * 0.8));
  }
  if (d === 1) return Math.min(50, Math.round(r < 8 ? 34 + r * 1.4 + k * 1.6 : 45 + (r - 8) * 0.3 + k * 0.3));
  return Math.min(50, Math.round(42 + r * 0.9 + k * 0.9));
}
function targetTime(d, r, i) { return (d === 0 && r === 0) ? 60 + i * 6 : 95 + i * 5; }

function trial(d, r, i, lvl, f, h, seeds) {
  let wins = 0, t = 0;
  for (let seed = 1; seed <= seeds; seed++) {
    const s = setup(d, r, i, lvl);
    const def = AW.stageDef(d, r, i);
    for (const l of def.lines) l.mag = Math.max(10, Math.round(l.mag * f));
    def.baseHp = Math.round(def.baseHp * h);
    const b = playBattle(s, def, AW.mulberry32(seed * 131 + i * 7 + r));
    if (b.state === 'won' && b.t < 400) { wins++; t += b.t; }
  }
  return { wins: wins, all: wins === seeds, t: wins ? t / wins : 999 };
}

// Tower health first (so a fight against weak Gloom takes ~60% of the goal), then the strongest Gloom that the
// scripted player still beats every time within the goal.
function tuneStage(d, r, i) {
  const T = targetLevel(d, r, i), goal = targetTime(d, r, i);
  let h = 1;
  for (let k = 0; k < 3; k++) {
    const w = trial(d, r, i, T, 0.35, h, 2);
    if (!w.all) { h *= 0.6; continue; }
    h = Math.max(0.15, Math.min(4, h * (0.6 * goal - 25) / Math.max(8, w.t - 25)));
  }
  let lo = 0.05, hi = 24;
  if (!trial(d, r, i, T, lo, h, 3).all) return { f: lo, h: h, T: T, t: 0, note: 'unwinnable' };
  for (let it = 0; it < 10; it++) {
    const mid = Math.sqrt(lo * hi);
    const res = trial(d, r, i, T, mid, h, 3);
    if (res.all && res.t <= goal) lo = mid; else hi = mid;
  }
  return { f: lo, h: h, T: T, t: trial(d, r, i, T, lo, h, 3).t };
}

if (require.main === module) {
  AW.setTune(null);
  // Tune against the base stages: CONFIG.challenge is applied on top of the tuning in the game.
  Object.assign(AW.CONFIG.challenge, { mag: 1, hp: 1, tempo: 1, region: {} });
  const which = (process.argv[2] || '0,1,2').split(',').map(Number);
  // Optional region range ("8-23") and a separate output file, so several tuners can run side by side.
  const span = (process.argv[3] || '0-' + (AW.CT.REGIONS.length - 1)).split('-').map(Number);
  const file = process.argv[4] ? path.resolve(process.argv[4]) : path.join(__dirname, '..', 'js', 'tune.js');
  let old = null;
  try { old = require(path.join(__dirname, '..', 'js', 'tune.js')); } catch (e) { old = null; }
  const out = { mag: [[], [], []], hp: [[], [], []] };
  for (let d = 0; d < 3; d++) for (let r = 0; r < AW.CT.REGIONS.length; r++) {
    out.mag[d][r] = (old && old.mag[d] && old.mag[d][r]) ? old.mag[d][r].slice() : new Array(12).fill(1);
    out.hp[d][r] = (old && old.hp[d] && old.hp[d][r]) ? old.hp[d][r].slice() : new Array(12).fill(1);
  }
  // Optional list of stages "d-r-i,..." to re-tune; every other stage keeps its current value.
  const only = process.argv[5] ? new Set(process.argv[5].split(',')) : null;
  for (const d of which) for (let r = span[0]; r <= span[1]; r++) {
    const row = [];
    for (let i = 0; i < 12; i++) {
      if (only && !only.has(d + '-' + r + '-' + i)) continue;
      const res = tuneStage(d, r, i);
      out.mag[d][r][i] = Math.round(res.f * 1000) / 1000;
      out.hp[d][r][i] = Math.round(res.h * 1000) / 1000;
      row.push(`L${res.T} ×${res.f.toFixed(2)} hp×${res.h.toFixed(2)} ${Math.round(res.t || 0)}s${res.note ? ' ' + res.note : ''}`);
    }
    if (!row.length) continue;
    console.log(d, r + 1, row.join(' | '));
    write(file, out);
  }
}

function write(file, out) {
  const rows = (a) => '[\n' + a.map((d) => '    [\n' + d.map((r) => '      [' + r.join(', ') + ']').join(',\n') + '\n    ]').join(',\n') + '\n  ]';
  fs.writeFileSync(file, '/* Animal Wars — stage tuning, generated by tools/tune.js. Do not edit by hand.\n' +
    ' * mag[difficulty][region][stage] scales Gloom strength, hp[...] scales tower health. */\n' +
    '(function (root) {\n  const T = {\n  mag: ' + rows(out.mag) + ',\n  hp: ' + rows(out.hp) + '\n  };\n' +
    '  if (typeof module !== \'undefined\' && module.exports) module.exports = T;\n  root.AW_TUNE = T;\n' +
    '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n');
}
module.exports = { targetLevel };
